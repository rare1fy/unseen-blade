/** Merge adjacent side-by-side stair cells sharing the same climb direction & elevation span into broad grand staircases. */
function mergeRamps(raw: RampRect[]): RampRect[] {
  const out: RampRect[] = [];
  const ns = raw.filter(r => r.dir === 'n' || r.dir === 's')
    .sort((a, b) => a.dir.localeCompare(b.dir) || (a.h0 ?? 0) - (b.h0 ?? 0) || (a.h1 ?? PLAT_H) - (b.h1 ?? PLAT_H) || a.z0 - b.z0 || a.x0 - b.x0);
  for (const r of ns) {
    const prev = out[out.length - 1];
    if (prev && prev.dir === r.dir && prev.h0 === r.h0 && prev.h1 === r.h1
      && Math.abs(prev.z0 - r.z0) < 0.02 && Math.abs(prev.z1 - r.z1) < 0.02 && Math.abs(prev.x1 - r.x0) < 0.02) {
      prev.x1 = r.x1;
    } else out.push({ ...r });
  }
  const ew = raw.filter(r => r.dir === 'e' || r.dir === 'w')
    .sort((a, b) => a.dir.localeCompare(b.dir) || (a.h0 ?? 0) - (b.h0 ?? 0) || (a.h1 ?? PLAT_H) - (b.h1 ?? PLAT_H) || a.x0 - b.x0 || a.z0 - b.z0);
  for (const r of ew) {
    const prev = out[out.length - 1];
    if (prev && prev.dir === r.dir && prev.h0 === r.h0 && prev.h1 === r.h1
      && Math.abs(prev.x0 - r.x0) < 0.02 && Math.abs(prev.x1 - r.x1) < 0.02 && Math.abs(prev.z1 - r.z0) < 0.02) {
      prev.z1 = r.z1;
    } else out.push({ ...r });
  }
  return out;
}
/** the rects (m) covering the map cells that pass test: runs along each row, runs of the same span in the rows below merged into one */
function rectsAt(rows: string[], test: (ch: string, c: number, r: number) => boolean, X0: number, Z0: number): Rect[] {
  const out: Rect[] = [];
  const emit = (q: { c0: number; c1: number; r0: number }, r1: number) => out.push({ x0: X0 + q.c0 * MAP_CELL, x1: X0 + (q.c1 + 1) * MAP_CELL, z0: Z0 + q.r0 * MAP_CELL, z1: Z0 + (r1 + 1) * MAP_CELL });
  let active: Array<{ c0: number; c1: number; r0: number }> = [];
  rows.forEach((row, r) => {
    const next: typeof active = [];
    for (let c = 0; c < row.length;) {
      if (!test(row[c], c, r)) { c++; continue; }
      let e = c; while (e + 1 < row.length && test(row[e + 1], e + 1, r)) e++;
      const i = active.findIndex(q => q.c0 === c && q.c1 === e);
      next.push(i >= 0 ? active.splice(i, 1)[0] : { c0: c, c1: e, r0: r });
      c = e + 1;
    }
    for (const q of active) emit(q, r - 1);
    active = next;
  });
  for (const q of active) emit(q, rows.length - 1);
  return out;
}

/** the map's plan on the stage set for it (call mapStage(m) first): solids, pits, bridges, stones, platforms, ramps, the moving pieces, the marks */
export function mapShape(m: RoomMap): ShapePlan {
  const rows = m.rows, W = rows[0].length, H = rows.length;
  if (rows.some(r => r.length !== W)) throw new Error(`map ${m.id}: rows of different widths`);
  const X0 = PLAY.x0, Z0 = PLAY.z0, box: Rect = { x0: PLAY.x0, x1: PLAY.x1, z0: PLAY.z0, z1: PLAY.z1 };
  const R = (a: string) => rectsAt(rows, ch => a.includes(ch), X0, Z0);
  const pitK: PitKind = m.pit ?? 'water';
  const explicitHigh = (c: number, r: number) => {
    if (c < 0 || r < 0 || c >= W || r >= H) return false;
    if (rows[r][c] === '^') return true;
    return !!m.high?.some(([c0, r0, c1, r1]) => c >= c0 && c <= c1 && r >= r0 && r <= r1);
  };
  const explicitLow = (c: number, r: number) => {
    if (c < 0 || r < 0 || c >= W || r >= H) return false;
    if (rows[r][c] === '+') return true;
    return !!m.low?.some(([c0, r0, c1, r1]) => c >= c0 && c <= c1 && r >= r0 && r <= r1);
  };
  // Elevation tier per map cell: 0 = ground, 1 = LOW_PLAT_H (0.56m), 2 = PLAT_H (1.12m).
  // Marks/props placed inside a terrace span automatically inherit that tier unless touching flat ground '.'.
  const cellTier = (c: number, r: number): 0 | 1 | 2 => {
    if (c < 0 || r < 0 || c >= W || r >= H) return 0;
    const ch = rows[r][c];
    if (ch === '/' || ch === ':' || '#~DG?X'.includes(ch)) return 0;
    if (explicitHigh(c, r)) return 2;
    if (explicitLow(c, r)) return 1;
    if (LOW_FLOOR.includes(ch)) return 0;
    let adjHigh = false, adjLow = false, adjGround = false;
    for (const [dc, dr] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) {
      const nc = c + dc, nr = r + dr;
      if (nc < 0 || nr < 0 || nc >= W || nr >= H) continue;
      if (explicitHigh(nc, nr)) adjHigh = true;
      else if (explicitLow(nc, nr)) adjLow = true;
      else if (LOW_FLOOR.includes(rows[nr][nc])) adjGround = true;
    }
    if (adjHigh && !adjGround && !adjLow) return 2;
    if (adjLow && !adjGround && !adjHigh) return 1;
    return 0;
  };
  const platforms: PlatformRect[] = [
    ...rectsAt(rows, (_ch, c, r) => cellTier(c, r) === 2, X0, Z0).map(q => ({ ...q, h: PLAT_H })),
    ...rectsAt(rows, (_ch, c, r) => cellTier(c, r) === 1, X0, Z0).map(q => ({ ...q, h: LOW_PLAT_H })),
  ];
  const rawRamps: RampRect[] = [];
  const stones: Rect[] = [];
  const fixed: FixedPlan = {
    id: m.id, bellTrees: m.bellTrees,
    closed: [...R('D').map(q => ({ ...q, kind: 'door' as const })), ...R('G').map(q => ({ ...q, kind: 'gate' as const })),
      ...R('?').map(q => ({ ...q, kind: 'hollow' as const })), ...R('X').map(q => ({ ...q, kind: 'barricade' as const }))],
    sunk: [...R('-').map(q => ({ ...q, kind: 'drop' as const })), ...R('w').map(q => ({ ...q, kind: 'flood' as const }))],
    exits: [], covers: [], props: [], marks: [], stages: m.stages,
  };
  let enter: [number, number] = [(X0 + PLAY.x1) / 2, PLAY.z1 - 2.5];
  const at = (c: number, r: number): [number, number] => [X0 + (c + 0.5) * MAP_CELL, Z0 + (r + 0.5) * MAP_CELL];
  const cellRect = (c: number, r: number): Rect => ({ x0: X0 + c * MAP_CELL, x1: X0 + (c + 1) * MAP_CELL, z0: Z0 + r * MAP_CELL, z1: Z0 + (r + 1) * MAP_CELL });
  const tierH = (t: 0 | 1 | 2) => t === 2 ? PLAT_H : t === 1 ? LOW_PLAT_H : 0;
  rows.forEach((row, r) => [...row].forEach((ch, c) => {
    const [x, z] = at(c, r);
    if (!'#~=-wDG?X'.includes(ch) && !FLOORISH.includes(ch)) throw new Error(`map ${m.id}: '${ch}' at ${c},${r}`);
    switch (ch) {
      case ':': stones.push(cellRect(c, r)); break;
      case '/': {
        const dirs: Array<[number, number, RampDir]> = [[0, -1, 'n'], [0, 1, 's'], [1, 0, 'e'], [-1, 0, 'w']];
        let best: { dir: RampDir; h0: number; h1: number; score: number } | null = null;
        for (const [dc, dr, dir] of dirs) {
          const tHi = cellTier(c + dc, r + dr);
          if (tHi <= 0) continue;
          const oc = c - dc, or = r - dr;
          const oppIn = oc >= 0 && oc < W && or >= 0 && or < H;
          const oppWalk = oppIn && !'#~DG?X'.includes(rows[or][oc]);
          const tLo = oppWalk ? cellTier(oc, or) : 0;
          if (tLo >= tHi) continue;
          const score = (oppWalk ? 10 : 0) + (tHi - tLo) * 2 + (tLo > 0 ? 1 : 0);
          if (!best || score > best.score) best = { dir, h0: tierH(tLo), h1: tierH(tHi), score };
        }
        if (!best) throw new Error(`map ${m.id}: ramp '/' at ${c},${r} touches no '^' or '+' terrace`);
        rawRamps.push({ ...cellRect(c, r), dir: best.dir, h0: best.h0, h1: best.h1 });
        break;
      }
      case 'S': enter = [x, z]; break;
      case 'E': {
        const side = r === 0 ? 'back' : c === 0 ? 'left' : c === W - 1 ? 'right' : null;
        if (!side) throw new Error(`map ${m.id}: E off the edge at ${c},${r}`);
        fixed.exits.push(side === 'back' ? { side, x, z: PLAY.z0 } : { side, x: side === 'left' ? PLAY.x0 : PLAY.x1, z });
        break;
      }
      case 'B': fixed.boss = [x, z]; break;
      case 'C': fixed.stations = [x, z]; break;
      case 'o': case '0': fixed.covers.push({ x, z, big: ch === '0', kind: m.coverKinds?.[fixed.covers.length % m.coverKinds.length] }); break;
      case 'j': fixed.props.push({ kind: 'small', x, z }); break;
      case 't': fixed.props.push({ kind: 'pillar', x, z }); break;
      case '!': fixed.props.push({ kind: 'oil', x, z }); break;
      case 'b': fixed.marks.push({ kind: 'bell', x, z }); break;
      case 'r': fixed.marks.push({ kind: 'rope', x, z }); break;
      case 'W': fixed.marks.push({ kind: 'wheel', x, z }); break;
      case 'P': fixed.marks.push({ kind: 'plate', x, z }); break;
      case '$': fixed.marks.push({ kind: 'reward', x, z }); break;
    }
  }));
  const ramps = mergeRamps(rawRamps);
  // the pits under bridges, drop-bridges and stepping stones too; a flooded path's pit is its own kind
  const pits = [...R('~=-:').map(q => ({ ...q, kind: pitK })), ...R('w').map(q => ({ ...q, kind: 'flood' as const }))];
  return {
    id: 'map', k: { x: 0, z: 0 }, box, solid: R('#'), pits, bridges: R('='),
    ...(stones.length ? { stones } : {}),
    ...(platforms.length ? { platforms } : {}),
    ...(ramps.length ? { ramps } : {}),
    enter, fixed,
  };
}

/** the exits a room uses, by the ids its spec asks for: one → the deepest E (the middle one of equals); two → the pair farthest apart,
 *  'left' the one further left. The E's not used are shut gates */
export function drawnExits(fx: FixedPlan, ids: Array<'left' | 'right' | 'back'>) {
  const out: Partial<Record<'left' | 'right' | 'back', FixedPlan['exits'][number]>> = {}, es = fx.exits;
  if (!ids.length || !es.length) return out;
  if (ids.length === 1 || es.length === 1) {
    const e = es.slice().sort((a, b) => a.z - b.z || Math.abs(a.x) - Math.abs(b.x))[0];
    out[ids[0]] = e; return out;
  }
  let best: [number, number] = [0, 1], bd = -1;
  for (let i = 0; i < es.length; i++) for (let j = i + 1; j < es.length; j++) { const d = Math.hypot(es[i].x - es[j].x, es[i].z - es[j].z); if (d > bd) { bd = d; best = [i, j]; } }
  const [a, b] = best.map(i => es[i]).sort((p, q) => p.x - q.x);
  out[ids[0]] = a; out[ids[1]] = b; return out;
}
