export const DIGIT_H = 7;
const gl = (ch: string) => DIGITS[ch] || DIGITS[' '];
/** 宽（格），字间 1 格 */
export function digitsW(t: string) { let w = 0; for (const ch of t) w += gl(ch)[0].length + 1; return Math.max(0, w - 1); }
/** 逐格回调：(x, y) 为格坐标（左上为原点） */
export function eachDigitCell(t: string, fn: (x: number, y: number) => void) {
  let cx = 0;
  for (const ch of t) { const g = gl(ch); g.forEach((row, y) => { for (let x = 0; x < row.length; x++) if (row[x] === '#') fn(cx + x, y); }); cx += g[0].length + 1; }
}
/** 该文本是否全部可用粗体数字画 */
export const isDigitText = (t: string) => [...t].every(ch => ch in DIGITS);
